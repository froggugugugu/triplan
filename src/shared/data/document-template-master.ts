import type { CreateDocumentTemplate } from '@/shared/types/document-template'

/**
 * ドキュメントテンプレートのマスタデータ。
 * IPA公開情報（共通フレーム2013=SLCP-JCF2013、非機能要求グレード2018、
 * 機能要件の合意形成ガイド、ユーザのための要件定義ガイド第2版等）を基に、
 * システム開発の各工程で作成する標準ドキュメントのマークダウン雛形を定義する。
 * 調査ノート: 非公開の設計文書
 *
 * 本文はOpen Knowledge Format（OKF）v0.2準拠:
 * - 先頭にYAML frontmatter。`type`が唯一の必須フィールド（本アプリでは`document`で統一）
 * - `title`/`description`/`tags`は推奨フィールド、`status`/`sources`はv0.2の
 *   ライフサイクル・プロベナンス信号
 * - タイトルはfrontmatterの`title`が担うため、本文はh2（`##`）から開始する
 * 出典: https://github.com/GoogleCloudPlatform/knowledge-catalog/blob/main/okf/SPEC.md
 *
 * 各テンプレートは**固定UUID**を持つ。`STANDARD_WBS_TEMPLATE`
 * （`wbs-template-master.ts`）のノードが`documentTemplateIds`でこのidを参照するため、
 * シードのたびにidが変わると紐づけが切れる。シード時は
 * `DataAdapter.create(..., { id: 固定UUID })`でこのidのまま永続化する
 * （`stores/document-template-store.ts`）。
 * idは`d0c00000-0000-4000-8000-0000000000NN`の連番形式（16進数のみ・UUID形式、
 * `docs/development-patterns.md`「E2Eシードデータの静かな読み込み失敗」の教訓に従い
 * 16進数以外の文字を含めない）。
 */
export interface DocumentTemplateMasterEntry extends CreateDocumentTemplate {
  id: string
}

/** 新規作成時の初期本文（OKF v0.2準拠の骨格） */
export function createEmptyOkfContent(title: string): string {
  return `---
type: document
title: ${title}
description: ""
tags: []
status: draft
sources: []
---

## 目的

（このドキュメントの目的を記述する）
`
}

function docId(suffix: string): string {
  return `d0c00000-0000-4000-8000-0000000000${suffix}`
}

